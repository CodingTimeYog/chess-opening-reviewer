"""Build the processed dataset: uv run python -m chess_trainer.data"""

import argparse
import json
from collections.abc import Callable
from pathlib import Path

import pandas as pd

from chess_trainer import config
from chess_trainer.data.ingest import STAGES, build_corpus
from chess_trainer.data.openings import OPENINGS
from chess_trainer.data.repertoire import build_tree

STAGE_LABELS = {
    "reached_root": f"reach the root position within {config.ROOT_WINDOW} plies",
    "both_rated": "both players rated",
    "rating_ok": "both players at or above the rating floor",
    "has_result": "decisive or drawn result",
    "unique": "after removing exact duplicates (final corpus)",
}


def stats_markdown(stats: dict, prep: dict, tree_size: int, sha: str) -> str:
    ops = list(OPENINGS.values())
    head = "| | " + " | ".join(o.name for o in ops) + " |\n|---|" + "---:|" * len(ops) + "\n"

    def row(label: str, get: Callable[[dict], int], fmt: str = ",") -> str:
        cells = " | ".join(format(get(stats["openings"][o.id]), fmt) for o in ops)
        return f"| {label} | {cells} |\n"

    out = [
        "# Data statistics\n\n",
        f"Generated by `python -m chess_trainer.data` at git `{sha}`, seed {stats['seed']}, "
        f"positions truncated at ply {stats['max_ply']}.\n\n",
        f"Corpus: OTB master games, {stats['parsed']:,} parsed "
        f"({stats['parse_errors']:,} dropped for illegal moves, "
        f"{stats['non_standard_start']:,} for a non-standard start).\n\n",
        "## Filter funnel (games remaining after each stage)\n\n",
        head,
        row("rating floor, both players", lambda e: e["min_elo"], "d"),
    ]
    out += [row(STAGE_LABELS[s], lambda e, s=s: e["stages"][s]) for s in STAGES]
    out += ["\n## Game-level split (80/10/10 within each opening)\n\n", head]
    for split in ("train", "val", "test"):
        out.append(row(f"{split} games", lambda e, s=split: e["splits"][s]["games"]))
        out.append(row(f"{split} positions", lambda e, s=split: e["splits"][s]["positions"]))
        if split != "train":
            out.append(
                row(
                    f"{split} strict positions (never seen in train)",
                    lambda e, s=split: e["splits"][s]["strict_positions"],
                )
            )
    out.append(row("unique positions, all splits", lambda e: e["unique_positions"]))
    out += [
        "\n## Repertoire tree (prep PGNs)\n\n",
        f"- chapters read: {prep['chapters']:,}\n",
        *(f"- kept, {OPENINGS[k].name}: {v:,}\n" for k, v in prep["kept"].items()),
        f"- skipped, main line never reaches a root: {prep['skipped_off_root']:,}\n",
        f"- skipped, starts from a FEN (puzzles): {prep['skipped_fen']:,}\n",
        f"- positions in tree: {tree_size:,}\n",
    ]
    return "".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the processed dataset from data/raw.")
    parser.add_argument("--raw", type=Path, default=config.RAW_DIR)
    parser.add_argument("--out", type=Path, default=config.PROCESSED_DIR)
    parser.add_argument("--results", type=Path, default=config.RESULTS_DIR)
    parser.add_argument("--seed", type=int, default=config.SEED)
    parser.add_argument(
        "--games-only",
        action="store_true",
        help="rewrite only games.parquet, after checking ids and splits are unchanged",
    )
    args = parser.parse_args()

    masters = sorted((args.raw / "masters").glob("*.pgn"))
    games, positions, stats = build_corpus(masters, seed=args.seed)
    tree, prep = build_tree(sorted((args.raw / "prep").glob("*.pgn")))
    sha = config.git_sha()

    args.out.mkdir(parents=True, exist_ok=True)
    args.results.mkdir(parents=True, exist_ok=True)
    if args.games_only:
        old = pd.read_parquet(args.out / "games.parquet")
        same = (
            old.set_index("game_id")["split"]
            .sort_index()
            .equals(games.set_index("game_id")["split"].sort_index())
        )
        if not same:
            raise SystemExit("game ids or splits changed: run the full pipeline instead")
        games.to_parquet(args.out / "games.parquet", index=False)
        print(f"games.parquet rewritten: {len(games):,} games, columns {list(games.columns)}")
        return
    games.to_parquet(args.out / "games.parquet", index=False)
    positions.to_parquet(args.out / "positions.parquet", index=False)
    (args.out / "repertoire.json").write_text(json.dumps(tree), encoding="utf-8")
    (args.out / "stats.json").write_text(
        json.dumps({"git_sha": sha, "corpus": stats, "prep": prep}, indent=2), encoding="utf-8"
    )
    report = stats_markdown(stats, prep, len(tree), sha)
    (args.results / "data_stats.md").write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
